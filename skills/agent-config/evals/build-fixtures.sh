#!/usr/bin/env bash
# Build the on-disk fixture repos that agent-config's evals (evals.json) run against.
#
# Usage: bash evals/build-fixtures.sh <dest-dir> [fixture ...]
#   With no fixture names, builds all of them. Each lands in <dest-dir>/<fixture>/ as a
#   git repo with one commit and no remote.
#
# Build fixtures OUTSIDE any directory that has a CLAUDE.md above it (for example, not
# inside this skills repo). Otherwise the ancestor file shadows AGENTS.md, and every
# case measures that instead of the skill.
set -euo pipefail

ALL="pnpm-fresh uv-claude-only go-bare audit-shadowed npm-local-shadow npm-symlinked"

if [ $# -lt 1 ]; then
  echo "Error: missing destination directory." >&2
  echo "Usage: bash evals/build-fixtures.sh <dest-dir> [fixture ...]" >&2
  echo "Fixtures: $ALL" >&2
  exit 1
fi
dest="$1"; shift
fixtures="${*:-$ALL}"
mkdir -p "$dest"

commit_all() {
  git init -q
  git add -A
  git -c user.name=fixture -c user.email=fixture commit -qm "fixture: initial state"
}

pnpm_project() {
  mkdir -p src/api src/generated .github/workflows
  cat > package.json <<'EOF'
{
  "name": "invoice-api",
  "private": true,
  "packageManager": "pnpm@9.12.0",
  "engines": { "node": ">=20" },
  "scripts": {
    "dev": "tsx watch src/server.ts",
    "build": "tsc -p tsconfig.build.json",
    "test": "vitest run",
    "lint": "eslint .",
    "typecheck": "tsc --noEmit",
    "codegen": "openapi-typescript openapi.yaml -o src/generated/api.ts"
  },
  "devDependencies": { "typescript": "^5.6.0", "vitest": "^2.1.0", "eslint": "^9.12.0", "tsx": "^4.19.0" }
}
EOF
  printf 'lockfileVersion: "9.0"\n' > pnpm-lock.yaml
  printf '{ "compilerOptions": { "strict": true, "module": "NodeNext", "target": "ES2022" } }\n' > tsconfig.json
  printf '# invoice-api\n\nHTTP API for issuing and tracking invoices.\n\nRun `pnpm install`, then `pnpm dev`.\n' > README.md
  printf 'export class AppError extends Error {\n  constructor(public code: string, message: string) { super(message); }\n}\n' > src/errors.ts
  printf 'import { AppError } from "../errors";\nexport function getUser(id: string) {\n  if (!id) throw new AppError("bad_request", "id required");\n  return { id };\n}\n' > src/api/users.ts
  printf 'import { expect, test } from "vitest";\nimport { getUser } from "./users";\ntest("getUser", () => { expect(getUser("1")).toEqual({ id: "1" }); });\n' > src/api/users.test.ts
  printf '// AUTO-GENERATED by `pnpm codegen` from openapi.yaml. Do not edit by hand.\nexport type User = { id: string };\n' > src/generated/api.ts
  printf 'import { getUser } from "./api/users";\nconsole.log(getUser("1"));\n' > src/server.ts
  printf 'openapi: 3.1.0\ninfo: { title: invoice-api, version: 1.0.0 }\npaths: {}\n' > openapi.yaml
  printf 'DATABASE_URL=postgres://localhost:5432/invoices\n' > .env.example
  printf 'node_modules/\n.env\n' > .gitignore
  cat > .github/workflows/ci.yml <<'EOF'
name: ci
on: [push, pull_request]
jobs:
  check:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: pnpm/action-setup@v4
      - uses: actions/setup-node@v4
        with: { node-version: 20, cache: pnpm }
      - run: pnpm install --frozen-lockfile
      - run: pnpm lint
      - run: pnpm typecheck
      - run: pnpm test
EOF
}

npm_project() {
  mkdir -p src
  cat > package.json <<'EOF'
{
  "name": "widget-ui",
  "private": true,
  "scripts": { "build": "webpack --mode production", "test": "jest", "lint": "eslint src" },
  "devDependencies": { "jest": "^29.7.0", "eslint": "^9.12.0", "webpack": "^5.95.0" }
}
EOF
  printf '{ "lockfileVersion": 3 }\n' > package-lock.json
  printf 'export const add = (a, b) => a + b;\n' > src/math.js
  printf 'import { add } from "./math";\ntest("add", () => expect(add(1, 2)).toBe(3));\n' > src/math.test.js
  printf '# widget-ui\n\nReusable UI widgets.\n' > README.md
}

build_one() {
  case "$1" in
    pnpm-fresh)
      pnpm_project
      ;;
    uv-claude-only)
      mkdir -p src/ledger/migrations tests .github/workflows
      cat > pyproject.toml <<'EOF'
[project]
name = "ledger"
version = "0.4.0"
requires-python = ">=3.12"
dependencies = []

[dependency-groups]
dev = ["pytest>=8", "ruff>=0.7", "mypy>=1.13"]

[tool.pytest.ini_options]
testpaths = ["tests"]
EOF
      printf 'version = 1\n' > uv.lock
      printf 'from decimal import Decimal\n\ndef balance(entries):\n    return sum((Decimal(e) for e in entries), Decimal("0"))\n' > src/ledger/__init__.py
      printf 'CREATE TABLE accounts (id INTEGER PRIMARY KEY, name TEXT NOT NULL);\n' > src/ledger/migrations/0001_init.sql
      printf 'from ledger import balance\n\ndef test_balance():\n    assert str(balance(["1.10", "2.20"])) == "3.30"\n' > tests/test_ledger.py
      cat > .github/workflows/ci.yml <<'EOF'
name: ci
on: [push, pull_request]
jobs:
  check:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: astral-sh/setup-uv@v3
      - run: uv sync --frozen
      - run: uv run ruff check .
      - run: uv run mypy src
      - run: uv run pytest -q
EOF
      cat > CLAUDE.md <<'EOF'
# CLAUDE.md

## Overview
Ledger is a Python 3.12 library for double-entry bookkeeping.

## Project structure
```
src/ledger/
  __init__.py
  migrations/
tests/
```

## Commands
- Install deps: `uv sync`
- Run tests: `uv run pytest -q`
- Single test: `uv run pytest tests/test_ledger.py::test_balance -q`
- Lint: `uv run ruff check .`
- Types: `uv run mypy src`

## Rules
- Use uv, never pip.
- Never edit a migration that has been merged; add a new one.
- Money is `Decimal`, never `float`.
- Write clean, readable code.

## Claude
- Use plan mode before touching `src/ledger/migrations/`.
- Use the /release skill to cut releases.
EOF
      ;;
    go-bare)
      mkdir -p internal/store .github/workflows
      printf 'module example.com/shortener\n\ngo 1.23\n' > go.mod
      printf 'package main\n\nimport "fmt"\n\nfunc main() { fmt.Println("shortener") }\n' > main.go
      printf 'package store\n\nfunc Key(url string) string { return url[:1] }\n' > internal/store/store.go
      printf 'package store\n\nimport "testing"\n\nfunc TestKey(t *testing.T) {\n\tif Key("abc") != "a" {\n\t\tt.Fatal("bad key")\n\t}\n}\n' > internal/store/store_test.go
      printf 'test:\n\tgo test ./...\n\nlint:\n\tgolangci-lint run\n' > Makefile
      printf '# shortener\n\nA URL shortener service.\n' > README.md
      ;;
    audit-shadowed)
      pnpm_project
      cat > AGENTS.md <<'EOF'
# AGENTS.md

## Commands
- Install: `pnpm install`
- Test one: `pnpm vitest run <file>`
- Test all: `pnpm test`
- Lint / types: `pnpm lint` · `pnpm typecheck`

## Constraints
- Use pnpm, not npm.
- Never edit `src/generated/`; run `pnpm codegen`.

## Done when
- `pnpm lint && pnpm typecheck && pnpm test` pass
EOF
      cat > CLAUDE.md <<'EOF'
# CLAUDE.md

Read AGENTS.md for all project rules.

- Use pnpm, not npm.
- Source lives in src/, tests next to the code, generated types in src/generated/, CI in .github/workflows/.
EOF
      ;;
    npm-local-shadow)
      npm_project
      printf 'node_modules/\nCLAUDE.local.md\n' > .gitignore
      commit_all
      printf '# My notes\n- My sandbox API: http://localhost:4010\n' > CLAUDE.local.md
      return 0
      ;;
    npm-symlinked)
      npm_project
      rm -f package-lock.json
      printf 'lockfileVersion: "9.0"\n' > pnpm-lock.yaml
      python3 - <<'EOF'
import json
p = json.load(open("package.json"))
p["packageManager"] = "pnpm@9.12.0"
json.dump(p, open("package.json", "w"), indent=2)
EOF
      cat > AGENTS.md <<'EOF'
# AGENTS.md

## Commands
- Install: `npm install`
- Test one: `npx jest src/math.test.js`
- Test all: `npm test`
- Lint: `npm run lint`

## Done when
- `npm run lint && npm test` pass
EOF
      ln -s AGENTS.md CLAUDE.md
      ;;
  esac
  commit_all
}

for f in $fixtures; do
  case " $ALL " in
    *" $f "*) ;;
    *) echo "Error: unknown fixture '$f'. Valid fixtures: $ALL" >&2; exit 1 ;;
  esac
done

for f in $fixtures; do
  target="$dest/$f"
  if [ -e "$target" ]; then
    echo "Error: $target already exists. Remove it or choose another destination directory." >&2
    exit 1
  fi
  mkdir -p "$target"
  (cd "$target" && build_one "$f")
  echo "built $target"
done
